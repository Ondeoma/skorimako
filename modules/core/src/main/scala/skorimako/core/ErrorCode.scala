  case TooManyRequests extends ErrorCode("SKORIMAKO-1011", 429, "短い時間に要求が多すぎます。しばらく待ってからお試しください")
  case OidcNotConfigured extends ErrorCode("SKORIMAKO-1101", 503, "OIDC が設定されていません")
  case LoginExpired extends ErrorCode("SKORIMAKO-1102", 400, "ログインの有効期限が切れました。もう一度ログインしてください")
  case LoginFailed extends ErrorCode("SKORIMAKO-1103", 401, "ログインできませんでした")
  case UserDisabled extends ErrorCode("SKORIMAKO-1104", 403, "このユーザーは無効にされています")
  case LoginCodeStateRequired extends ErrorCode("SKORIMAKO-1105", 400, "code と state が必要です")
  case NameRequired extends ErrorCode("SKORIMAKO-1201", 400, "名前を入力してください")
