  case ApiKeyNotFound extends ErrorCode("SKORIMAKO-1205", 404, "APIキーが見つかりません")
  case CannotChangeOwnRole extends ErrorCode("SKORIMAKO-1206", 400, "自分の権限は変えられません")
  case UserNotFound extends ErrorCode("SKORIMAKO-1207", 404, "ユーザーが見つかりません")
  case IngestApiKeyRequired
    extends ErrorCode("SKORIMAKO-2001", 401, "APIキー（ingest スコープ）を Authorization: Bearer で送ってください")
  case IngestScopeRequired extends ErrorCode("SKORIMAKO-2002", 403, "このAPIキーでは取り込めません（ingest か write スコープが必要です）")
  case IngestPromApiKeyRequired extends ErrorCode("SKORIMAKO-2003", 401, "APIキー（ingest スコープ）が必要です")
  case IngestPayloadInvalid extends ErrorCode("SKORIMAKO-2004", 400, "送られたデータを読めません")
