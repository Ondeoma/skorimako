 * 7xxx: ノード間の問い合わせ, 9xxx: サーバー内部・バックグラウンドの処理.
 * Prometheus 互換の API・MCP（JSON-RPC）・OAuth の応答は、それぞれの決まりの形のまま（ここのコードは使わない）.
 */
